/** Right-to-left locales: layout sets dir="rtl" for these. */
export const RTL_LOCALES = new Set(["ar", "he", "fa", "ur", "ps", "dv", "yi"]);
export function isRtlLocale(locale: string): boolean {
  return RTL_LOCALES.has(locale);
}

/** Primary official locale for a country (unsuppported-safe: may lack a dictionary). */
export function countryLocale(countryCode?: string | null): string {
  const cc = (countryCode || "").toLowerCase();
  return COUNTRY_LOCALE[cc] || "en";
}

